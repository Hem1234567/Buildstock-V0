enum ThermalWidth { mm58, mm80 }

/// Fonts are embedded so a PDF renders identically on a device that has no
/// Tamil or Latin fonts installed. Hind Madurai covers Tamil and Latin.
class InvoiceFonts {
  static pw.Font? _regular;
  static pw.Font? _bold;

  static Future<(pw.Font, pw.Font)> load() async {
    if (_regular != null && _bold != null) return (_regular!, _bold!);
    final regular = await rootBundle.load(
      'assets/fonts/HindMadurai-Regular.ttf',
    );
    final bold = await rootBundle.load('assets/fonts/HindMadurai-Bold.ttf');
    _regular = pw.Font.ttf(regular);
    _bold = pw.Font.ttf(bold);
    return (_regular!, _bold!);
  }
}

class InvoicePdfBuilder {
  static const PdfColor _muted = PdfColor.fromInt(0xFF666666);
  static const PdfColor _line = PdfColor.fromInt(0xFF444444);

  Future<Uint8List> buildA4(InvoiceDocument doc) async {
    final (regular, bold) = await InvoiceFonts.load();
    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(base: regular, bold: bold),
      title: '${doc.isEstimate ? 'Estimate' : 'Invoice'} ${doc.number}',
      author: doc.seller.name,
      creator: 'BuildStock',
    );

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(26, 26, 26, 30),
        header: (context) => context.pageNumber == 1
            ? pw.SizedBox()
            : pw.Container(
                alignment: pw.Alignment.centerRight,
                padding: const pw.EdgeInsets.only(bottom: 6),
                child: pw.Text(
                  '${doc.number} · Page ${context.pageNumber}',
                  style: const pw.TextStyle(fontSize: 8, color: _muted),
                ),
              ),
        footer: (context) => pw.Container(
          alignment: pw.Alignment.center,
          margin: const pw.EdgeInsets.only(top: 8),
          child: pw.Text(
            'Generated by BuildStock · ${AppDate.display(doc.date)}',
            style: const pw.TextStyle(fontSize: 7, color: _muted),
          ),
        ),
        build: (context) => [
          _header(doc),
          pw.SizedBox(height: 6),
          pw.Divider(color: _line, thickness: 1.2, height: 10),
          _documentInfo(doc),
          pw.SizedBox(height: 8),
          _buyer(doc),
          pw.SizedBox(height: 10),
          _items(doc),
          pw.SizedBox(height: 10),
          _totals(doc),
          pw.SizedBox(height: 14),
          _paymentAndSignature(doc),
          pw.SizedBox(height: 14),
          _footer(doc),
        ],
      ),
    );

    return pdf.save();
  }

  Future<Uint8List> buildThermal(
    InvoiceDocument doc,
    ThermalWidth width,
  ) async {
    final (regular, bold) = await InvoiceFonts.load();
    final pageWidth = width == ThermalWidth.mm58
        ? 58 * PdfPageFormat.mm
        : 80 * PdfPageFormat.mm;
    final pageHeight =
        (44 + doc.items.length * 7 + (doc.showUpiQr ? 40 : 0) + 58) *
        PdfPageFormat.mm;

    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(base: regular, bold: bold),
      title: '${doc.isEstimate ? 'Estimate' : 'Invoice'} ${doc.number}',
      creator: 'BuildStock',
    );

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat(
          pageWidth,
          pageHeight,
          marginAll: 4 * PdfPageFormat.mm,
        ),
        build: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.stretch,
          children: [
            pw.Center(
              child: pw.Text(
                doc.seller.name.toUpperCase(),
                textAlign: pw.TextAlign.center,
                style: pw.TextStyle(
                  fontSize: 10,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ),
            pw.Center(
              child: pw.Text(
                doc.seller.address,
                textAlign: pw.TextAlign.center,
                style: const pw.TextStyle(fontSize: 6.5),
              ),
            ),
            if (doc.seller.allPhones.isNotEmpty)
              pw.Center(
                child: pw.Text(
                  doc.seller.allPhones.join(' / '),
                  style: const pw.TextStyle(fontSize: 6.5),
                ),
              ),
            pw.SizedBox(height: 3),
            pw.Divider(color: _line, height: 6),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  doc.heading,
                  style: pw.TextStyle(
                    fontSize: 9,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.Text(doc.number, style: const pw.TextStyle(fontSize: 6.5)),
              ],
            ),
            pw.Text(
              'Date: ${AppDate.display(doc.date)}',
              style: const pw.TextStyle(fontSize: 6.5),
            ),
            pw.SizedBox(height: 2),
            pw.Text(
              'To: ${doc.buyer.name}',
              style: pw.TextStyle(fontSize: 7, fontWeight: pw.FontWeight.bold),
            ),
            if (doc.buyer.phone.isNotEmpty)
              pw.Text(
                'Ph: ${doc.buyer.phone}',
                style: const pw.TextStyle(fontSize: 6.5),
              ),
            pw.Divider(color: _line, height: 6),
            ...doc.items.map(
              (item) => pw.Padding(
                padding: const pw.EdgeInsets.symmetric(vertical: 1.5),
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      item.name,
                      style: pw.TextStyle(
                        fontSize: 7,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                      children: [
                        pw.Text(
                          '${Quantity.format(item.quantityMilli)} ${item.unit} x ${Money.plain(item.unitPricePaise)}',
                          style: const pw.TextStyle(fontSize: 6.5),
                        ),
                        pw.Text(
                          Money.plain(item.lineTotalPaise),
                          style: const pw.TextStyle(fontSize: 6.5),
                        ),
                      ],
                    ),
                  ],
                ),
              ),
            ),
            pw.Divider(color: _line, height: 6),
            _thermalRow('Subtotal', Money.plain(doc.subtotalPaise)),
            if (doc.discountPaise > 0)
              _thermalRow('Discount', '-${Money.plain(doc.discountPaise)}'),
            if (doc.isGst && doc.cgstPaise > 0)
              _thermalRow('CGST', Money.plain(doc.cgstPaise)),
            if (doc.isGst && doc.sgstPaise > 0)
              _thermalRow('SGST', Money.plain(doc.sgstPaise)),
            if (doc.isGst && doc.igstPaise > 0)
              _thermalRow('IGST', Money.plain(doc.igstPaise)),
            if (doc.roundOffPaise != 0)
              _thermalRow('Round off', Money.plain(doc.roundOffPaise)),
            pw.Divider(color: _line, height: 6),
            _thermalRow('TOTAL', Money.plain(doc.grandTotalPaise), bold: true),
            if (doc.amountPaidPaise > 0)
              _thermalRow('Paid', Money.plain(doc.amountPaidPaise)),
            _thermalRow(
              'Balance',
              Money.plain(doc.balanceDuePaise),
              bold: true,
            ),
            pw.SizedBox(height: 3),
            if (doc.showUpiQr) ...[
              pw.Center(
                child: pw.BarcodeWidget(
                  barcode: pw.Barcode.qrCode(),
                  data: UpiQr.paymentUri(
                    upiId: doc.upiId,
                    payeeName: doc.upiPayeeName,
                    amountPaise: doc.balanceDuePaise,
                    invoiceNumber: doc.number,
                    invoiceId: doc.id,
                  ),
                  width: 34 * PdfPageFormat.mm,
                  height: 34 * PdfPageFormat.mm,
                ),
              ),
              pw.Center(
                child: pw.Text(
                  'Scan to pay · ${Money.format(doc.balanceDuePaise)}',
                  style: const pw.TextStyle(fontSize: 6),
                ),
              ),
            ],
            if (!doc.isCancelled && doc.number.isNotEmpty) ...[
              pw.SizedBox(height: 3),
              pw.Center(
                child: pw.BarcodeWidget(
                  barcode: pw.Barcode.qrCode(),
                  data: InvoiceQr.encode(doc.number),
                  width: 22 * PdfPageFormat.mm,
                  height: 22 * PdfPageFormat.mm,
                ),
              ),
              pw.Center(
                child: pw.Text(
                  'Scan to open this bill',
                  style: const pw.TextStyle(fontSize: 5.5),
                ),
              ),
            ],
            pw.SizedBox(height: 4),
            pw.Center(
              child: pw.Text(
                'Thank you for your business',
                style: const pw.TextStyle(fontSize: 6.5),
              ),
            ),
            if (doc.isEstimate)
              pw.Center(
                child: pw.Text(
                  'ESTIMATE ONLY',
                  style: pw.TextStyle(
                    fontSize: 6.5,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
              ),
          ],
        ),
      ),
    );

    return pdf.save();
  }

  pw.Widget _thermalRow(String label, String value, {bool bold = false}) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Text(
          label,
          style: pw.TextStyle(
            fontSize: 7,
            fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
          ),
        ),
        pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 7,
            fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
          ),
        ),
      ],
    );
  }

  pw.Widget _header(InvoiceDocument doc) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        pw.Row(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Expanded(
              child: pw.Text(
                doc.heading,
                style: pw.TextStyle(
                  fontSize: 17,
                  fontWeight: pw.FontWeight.bold,
                  letterSpacing: 1.5,
                ),
              ),
            ),
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: doc.seller.allPhones
                  .map(
                    (phone) => pw.Text(
                      phone,
                      style: pw.TextStyle(
                        fontSize: 9,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                  )
                  .toList(),
            ),
          ],
        ),
        pw.SizedBox(height: 6),
        pw.Center(
          child: pw.Text(
            doc.seller.name.toUpperCase(),
            textAlign: pw.TextAlign.center,
            style: pw.TextStyle(
              fontSize: 22,
              fontWeight: pw.FontWeight.bold,
              letterSpacing: 1.6,
            ),
          ),
        ),
        pw.SizedBox(height: 2),
        pw.Center(
          child: pw.Text(
            'DEALERS IN CEMENT, BRICKS, SAND, JELLY AND GRAVEL',
            textAlign: pw.TextAlign.center,
            style: const pw.TextStyle(fontSize: 8.5),
          ),
        ),
        pw.Center(
          child: pw.Text(
            'AVAILABLE IN WHOLESALE AND RETAIL',
            textAlign: pw.TextAlign.center,
            style: pw.TextStyle(fontSize: 7.5, fontWeight: pw.FontWeight.bold),
          ),
        ),
        pw.SizedBox(height: 2),
        pw.Center(
          child: pw.Text(
            doc.seller.address,
            textAlign: pw.TextAlign.center,
            style: const pw.TextStyle(fontSize: 8.5),
          ),
        ),
        if (doc.seller.gstin.isNotEmpty)
          pw.Center(
            child: pw.Text(
              'GSTIN: ${doc.seller.gstin}',
              style: const pw.TextStyle(fontSize: 7.5),
            ),
          ),
      ],
    );
  }

  pw.Widget _documentInfo(InvoiceDocument doc) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Text(
          'Date: ${AppDate.display(doc.date)}',
          style: const pw.TextStyle(fontSize: 9),
        ),
        pw.Text(
          'Bill No: ${doc.number}',
          style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold),
        ),
      ],
    );
  }

  pw.Widget _buyer(InvoiceDocument doc) {
    final lines = <String>[
      if (doc.buyer.businessName.isNotEmpty) doc.buyer.businessName,
      if (doc.buyer.address.isNotEmpty) doc.buyer.address,
      if (doc.buyer.phone.isNotEmpty) 'Ph: ${doc.buyer.phone}',
      if (doc.buyer.gstin.isNotEmpty) 'GSTIN: ${doc.buyer.gstin}',
    ];
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(vertical: 4),
      decoration: const pw.BoxDecoration(
        border: pw.Border(top: pw.BorderSide(color: _line, width: 0.5)),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            'TO',
            style: const pw.TextStyle(fontSize: 6.5, color: _muted),
          ),
          pw.Text(
            doc.buyer.name,
            style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold),
          ),
          ...lines.map(
            (line) => pw.Text(line, style: const pw.TextStyle(fontSize: 8)),
          ),
        ],
      ),
    );
  }

  pw.Widget _items(InvoiceDocument doc) {
    final headerStyle = pw.TextStyle(
      fontSize: 8,
      fontWeight: pw.FontWeight.bold,
    );
    final cellStyle = const pw.TextStyle(fontSize: 8);

    return pw.Table(
      columnWidths: {
        0: const pw.FixedColumnWidth(26),
        1: const pw.FlexColumnWidth(),
        2: const pw.FixedColumnWidth(42),
        3: const pw.FixedColumnWidth(60),
        4: const pw.FixedColumnWidth(66),
      },
      border: pw.TableBorder.all(color: _line, width: 0.5),
      children: [
        pw.TableRow(
          decoration: const pw.BoxDecoration(
            color: PdfColor.fromInt(0xFFF1F1F1),
          ),
          children: [
            _cell('S.No', headerStyle, pw.TextAlign.center),
            _cell('Description', headerStyle, pw.TextAlign.left),
            _cell('Qty', headerStyle, pw.TextAlign.center),
            _cell('Rate', headerStyle, pw.TextAlign.right),
            _cell('Amount', headerStyle, pw.TextAlign.right),
          ],
        ),
        ...doc.items.asMap().entries.map((entry) {
          final index = entry.key + 1;
          final item = entry.value;
          return pw.TableRow(
            children: [
              _cell('$index', cellStyle, pw.TextAlign.center),
              pw.Padding(
                padding: const pw.EdgeInsets.symmetric(
                  horizontal: 4,
                  vertical: 3,
                ),
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      item.name,
                      style: pw.TextStyle(
                        fontSize: 8.5,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    if (item.sku.isNotEmpty || item.hsnCode.isNotEmpty)
                      pw.Text(
                        [
                          if (item.sku.isNotEmpty) 'SKU ${item.sku}',
                          if (item.hsnCode.isNotEmpty) 'HSN ${item.hsnCode}',
                        ].join(' · '),
                        style: const pw.TextStyle(fontSize: 6.5, color: _muted),
                      ),
                  ],
                ),
              ),
              _cell(
                Quantity.format(item.quantityMilli),
                cellStyle,
                pw.TextAlign.center,
              ),
              _cell(
                Money.plain(item.unitPricePaise),
                cellStyle,
                pw.TextAlign.right,
              ),
              _cell(
                Money.plain(item.lineTotalPaise),
                pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold),
                pw.TextAlign.right,
              ),
            ],
          );
        }),
      ],
    );
  }

  pw.Widget _cell(String text, pw.TextStyle style, pw.TextAlign align) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
      child: pw.Text(text, style: style, textAlign: align),
    );
  }

  pw.Widget _totals(InvoiceDocument doc) {
    final rows = <(String, String, bool)>[
      ('Subtotal', Money.plain(doc.subtotalPaise), false),
      if (doc.discountPaise > 0)
        ('Discount', '-${Money.plain(doc.discountPaise)}', false),
      ('Taxable Amount', Money.plain(doc.taxablePaise), false),
      if (doc.isGst && doc.cgstPaise > 0)
        ('CGST', Money.plain(doc.cgstPaise), false),
      if (doc.isGst && doc.sgstPaise > 0)
        ('SGST', Money.plain(doc.sgstPaise), false),
      if (doc.isGst && doc.igstPaise > 0)
        ('IGST', Money.plain(doc.igstPaise), false),
      if (doc.roundOffPaise != 0)
        ('Round Off', Money.plain(doc.roundOffPaise), false),
      ('Grand Total', Money.plain(doc.grandTotalPaise), true),
      if (doc.amountPaidPaise > 0)
        ('Amount Paid', Money.plain(doc.amountPaidPaise), false),
      ('Balance Due', Money.plain(doc.balanceDuePaise), true),
    ];

    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Expanded(
          child: pw.Padding(
            padding: const pw.EdgeInsets.only(right: 12),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  'AMOUNT IN WORDS',
                  style: const pw.TextStyle(fontSize: 6.5, color: _muted),
                ),
                pw.SizedBox(height: 2),
                pw.Text(
                  doc.amountInWords,
                  style: pw.TextStyle(
                    fontSize: 8,
                    fontStyle: pw.FontStyle.italic,
                  ),
                ),
                if (doc.notes.isNotEmpty) ...[
                  pw.SizedBox(height: 6),
                  pw.Text(
                    'Notes: ${doc.notes}',
                    style: const pw.TextStyle(fontSize: 7),
                  ),
                ],
              ],
            ),
          ),
        ),
        pw.SizedBox(
          width: 190,
          child: pw.Column(
            children: rows.map((row) {
              return pw.Container(
                padding: const pw.EdgeInsets.symmetric(
                  horizontal: 5,
                  vertical: 2.5,
                ),
                decoration: pw.BoxDecoration(
                  border: pw.Border(
                    bottom: pw.BorderSide(
                      color: row.$3
                          ? _line
                          : const PdfColor.fromInt(0xFFDDDDDD),
                      width: row.$3 ? 1 : 0.4,
                    ),
                  ),
                ),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      row.$1,
                      style: pw.TextStyle(
                        fontSize: 8,
                        fontWeight: row.$3
                            ? pw.FontWeight.bold
                            : pw.FontWeight.normal,
                      ),
                    ),
                    pw.Text(
                      row.$2,
                      style: pw.TextStyle(
                        fontSize: row.$3 ? 9 : 8,
                        fontWeight: row.$3
                            ? pw.FontWeight.bold
                            : pw.FontWeight.normal,
                      ),
                    ),
                  ],
                ),
              );
            }).toList(),
          ),
        ),
      ],
    );
  }

  pw.Widget _paymentAndSignature(InvoiceDocument doc) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.end,
      children: [
        if (doc.showUpiQr)
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.BarcodeWidget(
                barcode: pw.Barcode.qrCode(),
                data: UpiQr.paymentUri(
                  upiId: doc.upiId,
                  payeeName: doc.upiPayeeName,
                  amountPaise: doc.balanceDuePaise,
                  invoiceNumber: doc.number,
                  invoiceId: doc.id,
                ),
                width: 64,
                height: 64,
              ),
              pw.SizedBox(height: 2),
              pw.Text(
                'Scan to pay ${Money.format(doc.balanceDuePaise)}',
                style: const pw.TextStyle(fontSize: 7),
              ),
            ],
          )
        else
          pw.Text(
            'Payment Mode: ${doc.paymentMethodLabel()}',
            style: const pw.TextStyle(fontSize: 8),
          ),
        pw.Spacer(),
        if (!doc.isCancelled && doc.number.isNotEmpty) ...[
          pw.Column(
            children: [
              pw.BarcodeWidget(
                barcode: pw.Barcode.qrCode(),
                data: InvoiceQr.encode(doc.number),
                width: 52,
                height: 52,
              ),
              pw.SizedBox(height: 2),
              pw.Text('Scan to open', style: const pw.TextStyle(fontSize: 6)),
            ],
          ),
          pw.Spacer(),
        ],
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            pw.SizedBox(height: 34),
            pw.Container(width: 140, height: 0.7, color: _line),
            pw.SizedBox(height: 2),
            pw.Text(
              'Authorized Signature',
              style: const pw.TextStyle(fontSize: 7.5),
            ),
            if (doc.seller.name.isNotEmpty)
              pw.Text(
                'For ${doc.seller.name}',
                style: const pw.TextStyle(fontSize: 6.5, color: _muted),
              ),
          ],
        ),
      ],
    );
  }

  pw.Widget _footer(InvoiceDocument doc) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        pw.Divider(color: const PdfColor.fromInt(0xFFDDDDDD), height: 8),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Expanded(
              child: pw.Text(
                'Goods once sold will not be taken back. Subject to Chennai jurisdiction.',
                style: const pw.TextStyle(fontSize: 6.5, color: _muted),
              ),
            ),
            if (doc.showUpiQr)
              pw.Text(
                'UPI: ${doc.upiId}',
                style: const pw.TextStyle(fontSize: 6.5, color: _muted),
              ),
          ],
        ),
        if (doc.isEstimate)
          pw.Padding(
            padding: const pw.EdgeInsets.only(top: 3),
            child: pw.Text(
              'This is an estimate, not a tax invoice.',
              style: pw.TextStyle(fontSize: 7, fontWeight: pw.FontWeight.bold),
            ),
          ),
      ],
    );
  }
}
